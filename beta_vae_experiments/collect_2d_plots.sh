#!/usr/bin/env bash
set -euo pipefail

project_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source_root="${1:-${project_root}/Real_Data_Latent_d8_FixedBeta_AbsoluteCoreMetrics_v4_MPS/epochs_50/plots}"
target_root="${2:-${project_root}/Real_Data_Latent_d8_FixedBeta_AbsoluteCoreMetrics_v4_MPS/epochs_50/comparison_2d_plots}"

if [[ ! -d "${source_root}" ]]; then
    echo "Plot source directory does not exist: ${source_root}" >&2
    exit 1
fi

mkdir -p "${target_root}"

manifest="${target_root}/plot_manifest.tsv"
temporary_manifest="${manifest}.tmp"
printf 'learning_rate\treduction\tloss\tbeta\tlabel\trun_config\tsource_path\tcomparison_path\n' > "${temporary_manifest}"

# Remove only links previously generated by this script. Original plots and
# regular files in the comparison directory are never deleted.
find "${target_root}" -maxdepth 1 -type l -name '*.png' -delete

beta_order() {
    case "$1" in
        0p0004) printf '01' ;;
        0p001)  printf '02' ;;
        0p002)  printf '03' ;;
        0p004)  printf '04' ;;
        0p008)  printf '05' ;;
        0p016)  printf '06' ;;
        0p032)  printf '07' ;;
        0p064)  printf '08' ;;
        0p1)    printf '09' ;;
        0p25)   printf '10' ;;
        0p5)    printf '11' ;;
        0p75)   printf '12' ;;
        1p0)    printf '13' ;;
        2p0)    printf '14' ;;
        4p0)    printf '15' ;;
        6p0)    printf '16' ;;
        8p0)    printf '17' ;;
        12p0)   printf '18' ;;
        16p0)   printf '19' ;;
        24p0)   printf '20' ;;
        32p0)   printf '21' ;;
        48p0)   printf '22' ;;
        64p0)   printf '23' ;;
        96p0)   printf '24' ;;
        128p0)  printf '25' ;;
        192p0)  printf '26' ;;
        256p0)  printf '27' ;;
        512p0)  printf '28' ;;
        *)      printf '99' ;;
    esac
}

collected=0
while IFS= read -r -d '' source_path; do
    run_config="$(basename "$(dirname "${source_path}")")"
    original_name="$(basename "${source_path}")"
    label="${original_name#2D-scatter_49_all_}"
    label="${label%.png}"

    loss="${run_config%%_lr-*}"
    learning_rate="${run_config#*_lr-}"
    learning_rate="${learning_rate%%_beta-*}"
    beta="${run_config#*_beta-}"
    beta="${beta%%_reduction-*}"
    reduction="${run_config#*_reduction-}"
    reduction="${reduction%%_seed-*}"
    order="$(beta_order "${beta}")"

    comparison_name="lr-${learning_rate}__${reduction}__${loss}__beta-${order}-${beta}__2D-${label}.png"
    comparison_path="${target_root}/${comparison_name}"

    ln -sfn "${source_path}" "${comparison_path}"
    printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
        "${learning_rate}" \
        "${reduction}" \
        "${loss}" \
        "${beta}" \
        "${label}" \
        "${run_config}" \
        "${source_path}" \
        "${comparison_path}" >> "${temporary_manifest}"
    collected=$((collected + 1))
done < <(
    find "${source_root}" -mindepth 2 -maxdepth 2 -type f \
        -name '2D-scatter_*.png' \
        -print0 \
        | sort -z
)

mv "${temporary_manifest}" "${manifest}"

echo "Collected ${collected} 2D plots."
echo "Target: ${target_root}"
echo "Manifest: ${manifest}"
